#!/usr/bin/env python3
"""Generate the ordered 1.21.4 entity dimensions used by native mob tracking.

Reproduce from the pinned local input with:
    npm --prefix tests/mineflayer ci
    python3 tools/gen_entity_dimensions.py

Use --check in CI to verify the checked-in dimensions against both the
version-pinned minecraft-data entity table and the canonical MobKind order in
docs/mob_stats_149.csv.
"""

import argparse
import csv
import json
import math
from pathlib import Path

from atomic_write import write_text_atomic


ROOT = Path(__file__).resolve().parent.parent
DATA_PACKAGE = ROOT / "tests/mineflayer/node_modules/minecraft-data"
DATA_ROOT = DATA_PACKAGE / "minecraft-data/data/pc/1.21.4"
MOB_ORDER = ROOT / "docs/mob_stats_149.csv"
OUTPUT = ROOT / "src/generated/EntityDimensions.hpp"
EXPECTED_PACKAGE_VERSION = "3.117.0"
EXPECTED_ENTITY_COUNT = 149

PARSER = argparse.ArgumentParser(description=__doc__)
PARSER.add_argument("--check", action="store_true")
ARGS = PARSER.parse_args()


def read_inputs():
    try:
        package = json.loads((DATA_PACKAGE / "package.json").read_text(
            encoding="utf-8"))
        entities = json.loads((DATA_ROOT / "entities.json").read_text(
            encoding="utf-8"))
        order_rows = list(csv.reader(
            line for line in MOB_ORDER.read_text(encoding="utf-8").splitlines()
            if line and not line.startswith("#")))
    except OSError as error:
        raise SystemExit(
            "pinned entity dimension input is missing; run "
            "`npm --prefix tests/mineflayer ci` first") from error

    if package.get("version") != EXPECTED_PACKAGE_VERSION:
        raise SystemExit(
            f"expected minecraft-data {EXPECTED_PACKAGE_VERSION}, "
            f"found {package.get('version')!r}")
    if not isinstance(entities, list) or not entities:
        raise SystemExit("entity dimensions source must be a non-empty array")
    if (not order_rows or order_rows[0][0] != "name" or
            any(not row or not row[0].startswith("minecraft:")
                for row in order_rows[1:])):
        raise SystemExit("mob_stats_149.csv has a malformed canonical name order")

    names = [row[0] for row in order_rows[1:]]
    if len(names) != EXPECTED_ENTITY_COUNT or len(set(names)) != len(names):
        raise SystemExit(
            f"expected {EXPECTED_ENTITY_COUNT} unique MobKind names, "
            f"found {len(names)}")
    return names, entities


def float_literal(value, name, field):
    if (isinstance(value, bool) or not isinstance(value, (float, int)) or
            not math.isfinite(value) or value < 0.0 or value > 64.0):
        raise SystemExit(f"{name} has invalid {field}: {value!r}")
    rendered = format(float(value), ".9g")
    if "." not in rendered and "e" not in rendered.lower():
        rendered += ".0"
    return rendered + "f"


def generate_header():
    names, entities = read_inputs()
    by_name = {}
    for entity in entities:
        if not isinstance(entity, dict) or not isinstance(entity.get("name"), str):
            raise SystemExit("entity dimension source contains a malformed entry")
        name = entity["name"]
        if name in by_name:
            raise SystemExit(f"entity dimension source repeats {name}")
        by_name[name] = entity

    rows = []
    for full_name in names:
        name = full_name.removeprefix("minecraft:")
        entity = by_name.get(name)
        # The native enum retains a generic boat alias alongside all 1.21.4
        # wood-specific types. Vanilla gives each boat variant identical size.
        if name == "boat" and entity is None:
            entity = by_name.get("oak_boat")
        if entity is None:
            raise SystemExit(f"missing 1.21.4 dimensions for {full_name}")
        width = float_literal(entity.get("width"), full_name, "width")
        height = float_literal(entity.get("height"), full_name, "height")
        rows.append(
            f'    {{"{full_name}", {width}, {height}}},')

    row_text = "\n".join(rows)
    return f'''// Generated by tools/gen_entity_dimensions.py. Do not edit.
// Source: minecraft-data {EXPECTED_PACKAGE_VERSION}, Minecraft 1.21.4.
#pragma once

#include <array>
#include <cstddef>
#include <string_view>

namespace cppfm::gen {{

struct MobCollisionDimensions {{
    std::string_view name;
    float width;
    float height;
}};

inline constexpr std::array<MobCollisionDimensions, {len(rows)}>
    kMobCollisionDimensions = {{{{
{row_text}
}}}};

inline constexpr MobCollisionDimensions kUnknownMobCollisionDimensions{{
    "", 0.6f, 1.8f}};

inline const MobCollisionDimensions& mobCollisionDimensions(
    const std::size_t mobKindIndex) noexcept {{
    return mobKindIndex < kMobCollisionDimensions.size()
        ? kMobCollisionDimensions[mobKindIndex]
        : kUnknownMobCollisionDimensions;
}}

}} // namespace cppfm::gen
'''


generated = generate_header()
if ARGS.check:
    if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != generated:
        raise SystemExit(
            f"{OUTPUT.relative_to(ROOT)} is stale; "
            "run tools/gen_entity_dimensions.py")
    print(f"verified {OUTPUT.relative_to(ROOT)}")
else:
    write_text_atomic(OUTPUT, generated)
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
