#!/usr/bin/env python3
"""Generate protocol-769 block IDs from pinned minecraft-data input.

Reproduce from a clean checkout with:
    npm --prefix tests/mineflayer ci
    python3 tools/gen_block_registry_ids.py

Set BLOCKS_JSON to override the pinned local dataset with another verified
PrismarineJS 1.21.4 blocks.json file.
"""
import argparse
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
PARSER = argparse.ArgumentParser(description=__doc__)
PARSER.add_argument(
    "--check", action="store_true",
    help="verify the checked-in header instead of rewriting it")
ARGS = PARSER.parse_args()
PINNED_MINECRAFT_DATA_VERSION = "3.117.0"
DATA_PACKAGE = os.path.join(
    HERE, "..", "tests", "mineflayer", "node_modules", "minecraft-data")
DEFAULT_SOURCE = os.path.join(
    DATA_PACKAGE, "minecraft-data", "data", "pc", "1.21.4", "blocks.json")
SOURCE = os.environ.get("BLOCKS_JSON", DEFAULT_SOURCE)
OUT = os.path.join(HERE, "..", "src", "generated", "BlockRegistryIds.hpp")

if "BLOCKS_JSON" not in os.environ:
    package_path = os.path.join(DATA_PACKAGE, "package.json")
    try:
        with open(package_path, encoding="utf-8") as package_file:
            package_version = json.load(package_file).get("version")
    except OSError as error:
        raise SystemExit(
            "pinned minecraft-data input is missing; run "
            "`npm --prefix tests/mineflayer ci` or set BLOCKS_JSON") from error
    if package_version != PINNED_MINECRAFT_DATA_VERSION:
        raise SystemExit(
            f"expected minecraft-data {PINNED_MINECRAFT_DATA_VERSION}, "
            f"found {package_version!r}; run `npm --prefix tests/mineflayer ci` "
            "or set BLOCKS_JSON")

with open(SOURCE, encoding="utf-8") as source:
    blocks = json.load(source)
blocks.sort(key=lambda block: int(block["id"]))
if [int(block["id"]) for block in blocks] != list(range(len(blocks))):
    raise ValueError("block registry IDs must be contiguous from zero")

names = ["minecraft:" + block["name"] for block in blocks]
rows = [f'    "{name}",' for name in names]
packed = "\n".join(
    "\n".join(rows[start:start + 4])
    for start in range(0, len(rows), 4)
)

header = f'''// GENERATED by tools/gen_block_registry_ids.py -- DO NOT EDIT BY HAND.
// Minecraft Java 1.21.4 / protocol 769 block registry ordering.
// Source: PrismarineJS minecraft-data blocks.json (clean-room dataset).
#pragma once

#include <array>
#include <cstdint>
#include <optional>
#include <string_view>

namespace cppfm::gen {{

inline constexpr std::array<std::string_view, {len(names)}> kBlockRegistryNames{{{{
{packed}
}}}};

inline constexpr std::string_view blockNameByRegistryId(
    std::uint32_t id) noexcept {{
    return id < kBlockRegistryNames.size()
        ? kBlockRegistryNames[id] : std::string_view{{}};
}}

inline constexpr std::optional<std::uint32_t> blockRegistryId(
    std::string_view name) noexcept {{
    for (std::uint32_t id = 0; id < kBlockRegistryNames.size(); ++id)
        if (kBlockRegistryNames[id] == name) return id;
    return std::nullopt;
}}

}} // namespace cppfm::gen
'''

if ARGS.check:
    try:
        with open(OUT, encoding="utf-8", newline="") as current_file:
            current = current_file.read()
    except OSError as error:
        raise SystemExit(f"generated header is missing: {OUT}") from error
    if current != header:
        raise SystemExit(
            f"generated header is stale: {OUT}; run tools/gen_block_registry_ids.py")
    print(f"verified {OUT}: {len(names)} block registry entries")
else:
    with open(OUT, "w", encoding="utf-8", newline="\n") as output:
        output.write(header)
    print(f"wrote {OUT}: {len(names)} block registry entries")
